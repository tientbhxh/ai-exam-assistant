-- 3. Tạo hàm kiểm tra đăng nhập (RPC) bảo mật
CREATE OR REPLACE FUNCTION check_login(p_username TEXT, p_password TEXT)
RETURNS TEXT AS $$
DECLARE
  v_role TEXT;
BEGIN
  -- Tìm kiếm tài khoản trùng khớp username và password
  SELECT role INTO v_role 
  FROM custom_users 
  WHERE username = p_username AND password = p_password;
  
  -- Trả về role (admin hoặc teacher), nếu sai sẽ trả về null
  RETURN v_role;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;
