-- 1. Tạo bảng lưu Trí nhớ AI
CREATE TABLE learned_rules (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rule TEXT NOT NULL UNIQUE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Bật bảo mật cho bảng learned_rules (Mọi người có thể đọc/ghi, phù hợp cho nội bộ)
ALTER TABLE learned_rules ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Cho phép đọc/ghi rules" ON learned_rules FOR ALL USING (true);


-- 2. Tạo bảng người dùng nội bộ (Custom Users)
CREATE TABLE custom_users (
  username TEXT PRIMARY KEY,
  password TEXT NOT NULL,
  role TEXT NOT NULL
);

